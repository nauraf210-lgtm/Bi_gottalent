    private void btnBeriNilaiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBeriNilaiActionPerformed
        // TODO add your handling code here: private void btnBeriNilaiActionPerformed(java.awt.event.ActionEvent evt) {                                             
        int baris = tblPesertaJuri.getSelectedRow();
        if (baris == -1) {
            JOptionPane.showMessageDialog(this, "Pilih data peserta di tabel terlebih dahulu!");
            return;
        }
        
        String idPendaftaran = model.getValueAt(baris, 0).toString();
        
        Object[] pilihanStatus = {"Lolos", "Tidak Lolos"};
        String statusBaru = (String) JOptionPane.showInputDialog(
            this, 
            "Pilih Keputusan Penilaian Juri:", 
            "Form Nilai Juri", 
            JOptionPane.QUESTION_MESSAGE, 
            null, 
            pilihanStatus, 
            pilihanStatus[0]
        );
        
        if (statusBaru != null) {
            String catatan = "";
            if (statusBaru.equals("Tidak Lolos")) {
                catatan = JOptionPane.showInputDialog(this, "Masukkan catatan/alasan kenapa tidak lolos:");
                if (catatan == null) {
                    catatan = "Tidak ada catatan.";
                }
            } else {
                catatan = "Selamat, Anda lolos tahap seleksi juri!";
            }
            
            try {
                Connection c = Koneksi.configDB();
                String sql = "UPDATE pendaftaran SET status=?, catatan=? WHERE id=?";
                PreparedStatement p = c.prepareStatement(sql);
                p.setString(1, statusBaru);
                p.setString(2, catatan);
                p.setString(3, idPendaftaran);
                p.executeUpdate();
                
                JOptionPane.showMessageDialog(this, "Penilaian berhasil disimpan!");
                loadDataPeserta();
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menyimpan nilai: " + e.getMessage());
            }
        }
    
    }//GEN-LAST:event_btnBeriNilaiActionPerformed

